/// كل الأقسام بترتيب ظهورها في الدليل.
List<String> helpSections() {
  final out = <String>[];
  for (final t in kHelpTopics) {
    if (!out.contains(t.section)) out.add(t.section);
  }
  return out;
}

/// كل نصوص الموضوع مجمّعة — بيستخدمها البحث.
List<String> helpHaystack(HelpTopic t) => [
      t.title,
      t.summary,
      t.section,
      t.keywords,
      ...t.steps,
      ...t.tips,
    ];
